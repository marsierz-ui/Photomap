"""Push the heat-map snapshot to R2, uploading only what changed.

Object layout in the bucket:
    index.html         the standalone viewer
    sw.js              its service worker, plus manifest.webmanifest and icons
    manifest.json      points, albums, stats (overwritten every sync)
    t/<hash>.jpg       content-addressed thumbnails (written once, never rewritten)

Only `manifest.json` is rewritten on a normal sync, so a run costs a handful of
Class A operations rather than one per photo.
"""
import datetime
import hashlib
import json
import os
import re
import shutil
import sqlite3
import threading
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from . import db, dupes, photometa, r2, scanner, snapshot, thumbs

try:
    from send2trash import send2trash

    RECYCLE_OK = True
except ImportError:
    RECYCLE_OK = False

VIEWER_DIR = Path(__file__).resolve().parent.parent / "viewer"
# The same Leaflet and MapLibre builds the desktop app runs. Published so the
# viewer has no CDN dependency: a cross-origin script is one the service worker
# cannot cache, which left the installed app with no map at all offline.
VENDOR_DIR = Path(__file__).resolve().parent.parent / "frontend" / "vendor"

# The viewer is a page plus the files that make it installable: a manifest, a
# service worker and two icons. They all land at the root of the bucket, which
# is what lets the service worker claim the whole origin as its scope.
VIEWER_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".webmanifest": "application/manifest+json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
}

# Kept in step with the Worker's own cap, which is the first thing a note has to
# get past. This is the backstop for an object written before that cap existed.
NOTE_MAX = 4000

# Most photos anyone would plausibly delete in one action from a phone. A larger
# request is far more likely to be a mistake than an intention.
CLOUD_DELETE_CAP = 200

# A dropped connection mid-run is normal against R2 over a long upload; only a
# key that fails every attempt is a real failure.
UPLOAD_TRIES = 4
UPLOAD_BACKOFF = 1.5  # seconds, doubled each retry

# A phone photo arrives as two objects: a small proxy first, so the map updates
# straight away, then the full-resolution original. Wait this long for the
# second half before settling for the proxy.
IMPORT_GRACE = 900  # seconds
# ...and give up on an import entirely after this, so half an upload cannot sit
# in the bucket forever. Measured from when THIS machine first saw the op, never
# from the phone's clock - a device an hour or a year fast would otherwise be
# permanently young and never expire.
IMPORT_DEADLINE = 7 * 86400
# Matches the Worker's cap, which an upload has to get past first. Generous
# enough for a 50MB phone photo, and well under the 100MB maximum request body a
# Worker can receive on the Free and Pro plans.
IMPORT_MAX_BYTES = 64 * 1024 * 1024
# <13-digit ms epoch>-<uuid4>, generated by the Worker. Anchored, so nothing
# client-supplied can widen it.
IMPORT_ID = re.compile(
    r"^\d{13}-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$"
)
IMPORT_STEM = re.compile(r"[^A-Za-z0-9_-]+")
# Only what Pillow can actually open here, so an import cannot introduce a file
# the scanner would then skip forever.
IMPORT_EXTS = photometa.IMAGE_EXTS
# Only stop early if something is systematically wrong, not for a rough patch.
MAX_FAILURES = 200

_state = {
    "running": False,
    "phase": "idle",
    "done": 0,
    "total": 0,
    "uploaded": 0,
    "skipped": 0,
    "deleted": 0,
    "bytes": 0,
    "points": 0,
    "received": None,
    "error": None,
    "started": None,
    "finished": None,
}
_lock = threading.Lock()
_thread: threading.Thread | None = None


def viewer_files() -> list[tuple[str, Path]]:
    """(bucket key, local file) for everything the viewer is made of.

    Its own files stay at the root, which is what lets the service worker claim
    the whole origin. The libraries keep their directory layout under `vendor/`
    because MapLibre resolves its worker against its own URL, so the three files
    it ships with have to stay side by side.
    """
    out: list[tuple[str, Path]] = []
    if VIEWER_DIR.is_dir():
        out += [
            (p.name, p)
            for p in sorted(VIEWER_DIR.iterdir())
            if p.is_file() and p.suffix in VIEWER_TYPES
        ]
    if VENDOR_DIR.is_dir():
        out += [
            (f"vendor/{p.relative_to(VENDOR_DIR).as_posix()}", p)
            for p in sorted(VENDOR_DIR.rglob("*"))
            if p.is_file() and p.suffix in VIEWER_TYPES
        ]
    return out


def status() -> dict:
    with _lock:
        return dict(_state)


def _set(**kwargs) -> None:
    with _lock:
        _state.update(kwargs)


def config() -> dict:
    return {
        "account_id": db.get_setting("r2_account_id", "") or "",
        "bucket": db.get_setting("r2_bucket", "") or "",
        "access_key_id": db.get_setting("r2_access_key_id", "") or "",
        "secret_key": db.get_setting("r2_secret_key", "") or "",
    }


def configured() -> bool:
    return all(config().values())


def client() -> r2.Bucket:
    cfg = config()
    return r2.Bucket(cfg["account_id"], cfg["bucket"], cfg["access_key_id"], cfg["secret_key"])


def start() -> bool:
    global _thread
    with _lock:
        if _state["running"]:
            return False
        _state.update(
            running=True, phase="building", done=0, total=0, uploaded=0, skipped=0,
            deleted=0, bytes=0, points=0, received=None, error=None,
            started=time.time(), finished=None,
        )
    _thread = threading.Thread(target=_run, daemon=True)
    _thread.start()
    return True


def _apply_inbox(bucket, conn) -> dict:
    """Pull changes made in the cloud viewer and apply them locally.

    Every operation is idempotent, so a change that was applied but whose inbox
    object failed to delete does no harm when it is seen again.
    """
    applied = {"albums": 0, "favourites": 0, "duplicates": 0, "deleted": 0,
               "notes": 0, "imported": 0, "already_here": 0, "failed": 0}
    try:
        keys = bucket.list_keys(prefix=snapshot.INBOX_PREFIX)
    except r2.R2Error:
        return applied

    # Seconds, matching the manifest field. Imports still waiting for their
    # other half hold the watermark back, so the viewer keeps its local copy of
    # anything this sync did not finish.
    waiting: list[int] = []
    for key in sorted(keys):
        # Only JSON ops live in the inbox: image bytes go under import/. Anything
        # else here is not ours to parse, and must not be deleted either.
        if not key.endswith(".json"):
            continue
        keep = False
        try:
            change = json.loads(bucket.get(key))
        except Exception:
            applied["failed"] += 1
            continue

        try:
            op = change.get("op")
            ids = [int(i) for i in change.get("photo_ids", [])]
            with db.write_lock:
                if op == "album_add" and ids:
                    conn.executemany(
                        "INSERT OR IGNORE INTO album_photos(album_id, photo_id) VALUES (?,?)",
                        [(int(change["album_id"]), i) for i in ids],
                    )
                    applied["albums"] += len(ids)
                elif op == "album_remove" and ids:
                    conn.executemany(
                        "DELETE FROM album_photos WHERE album_id=? AND photo_id=?",
                        [(int(change["album_id"]), i) for i in ids],
                    )
                    applied["albums"] += len(ids)
                elif op == "album_create":
                    name = str(change.get("name", "")).strip()
                    if name:
                        cur = conn.execute(
                            "INSERT OR IGNORE INTO albums(name, color, created_ts) VALUES (?,?,?)",
                            (name, change.get("color") or "#ff5a5f", int(time.time())),
                        )
                        album_id = cur.lastrowid or conn.execute(
                            "SELECT id FROM albums WHERE name=?", (name,)
                        ).fetchone()["id"]
                        conn.executemany(
                            "INSERT OR IGNORE INTO album_photos(album_id, photo_id) VALUES (?,?)",
                            [(album_id, i) for i in ids],
                        )
                        applied["albums"] += 1
                elif op == "favorite" and ids:
                    value = 1 if change.get("value") else 0
                    conn.executemany(
                        "UPDATE photos SET favorite=? WHERE id=?", [(value, i) for i in ids]
                    )
                    applied["favourites"] += len(ids)
                elif op == "photo_note" and ids:
                    # Empty clears it, and is stored as NULL like the desktop
                    # does, so the search LIKE never matches a blank note.
                    note = str(change.get("note", "")).strip()[:NOTE_MAX] or None
                    conn.executemany(
                        "UPDATE photos SET note=? WHERE id=?", [(note, i) for i in ids]
                    )
                    applied["notes"] += len(ids)
                conn.commit()

            if op == "dupe_resolve":
                applied["duplicates"] += _resolve_duplicate(conn, change)
            elif op == "photo_delete":
                applied["deleted"] += _delete_photos(conn, change)
            elif op == "photo_import":
                landed, keep, duplicate = _import_photo(conn, bucket, change)
                applied["imported"] += landed
                applied["already_here"] += duplicate
        except Exception:
            applied["failed"] += 1

        if keep:
            # Its other half is still on the way. The only op that is not
            # deleted on sight, so the photo survives a sync that was too early.
            # queued_ts is the Worker's Date.now(), i.e. milliseconds; the
            # watermark is seconds, and this is the one place it is converted.
            waiting.append(int(change.get("queued_ts", 0)) // 1000)
            continue
        try:
            bucket.delete(key)
        except r2.R2Error:
            pass  # re-applied harmlessly next sync

    db.set_setting("import_watermark", min(waiting) if waiting else int(time.time()))
    return applied


def _trash_photo(conn, photo_id: int, path: str) -> bool:
    """Move one file to the recycle bin and drop it from the index.

    Nothing here deletes permanently: the file is always recoverable from the
    bin (or data/trash when Send2Trash is unavailable).
    """
    try:
        if os.path.exists(path):
            if RECYCLE_OK:
                send2trash(os.path.normpath(path))
            else:
                db.TRASH_DIR.mkdir(parents=True, exist_ok=True)
                shutil.move(path, db.TRASH_DIR / f"{photo_id}_{os.path.basename(path)}")
    except Exception:
        return False
    with db.write_lock:
        conn.execute("DELETE FROM album_photos WHERE photo_id=?", (photo_id,))
        conn.execute("DELETE FROM photos WHERE id=?", (photo_id,))
        conn.commit()
    thumbs.drop(photo_id)
    return True


def _resolve_duplicate(conn, change) -> int:
    """Delete the extra copies of one duplicate set, only if one copy survives."""
    digest = str(change.get("hash", ""))
    keep_id = int(change.get("keep_id", 0))
    rows = conn.execute(
        "SELECT id, path FROM photos WHERE content_hash=? AND missing=0", (digest,)
    ).fetchall()
    ids = [r["id"] for r in rows]
    if len(ids) < 2 or keep_id not in ids:
        return 0
    return sum(
        _trash_photo(conn, r["id"], r["path"]) for r in rows if r["id"] != keep_id
    )


def _delete_photos(conn, change) -> int:
    """Delete ordinary photos requested from the cloud viewer.

    Deliberately hard to trigger by accident:
      - off unless this machine has opted in (`cloud_delete_enabled`);
      - the request must state how many photos it means to delete, and the
        count has to match the id list exactly;
      - batches are capped, so a malformed or replayed request cannot sweep
        the library;
      - files go to the recycle bin, never straight to permanent deletion.
    """
    if db.get_setting("cloud_delete_enabled", "0") != "1":
        return 0
    ids = [int(i) for i in change.get("photo_ids", [])]
    if not ids or len(ids) > CLOUD_DELETE_CAP:
        return 0
    try:
        stated = int(change.get("confirm_count", -1))
    except (TypeError, ValueError):
        return 0
    if stated != len(ids):
        return 0

    placeholders = ",".join("?" * len(ids))
    rows = conn.execute(
        f"SELECT id, path FROM photos WHERE missing=0 AND id IN ({placeholders})", ids
    ).fetchall()
    return sum(_trash_photo(conn, r["id"], r["path"]) for r in rows)


def _import_first_seen(conn, uid: str, now: int) -> int:
    """When this machine first saw one queued import, in seconds.

    Recorded locally on purpose. The upload's id carries the phone's clock, and
    a phone whose clock is fast would otherwise never reach the deadline.
    """
    with db.write_lock:
        conn.execute(
            "INSERT OR IGNORE INTO import_seen(uid, first_ts) VALUES (?,?)", (uid, now)
        )
        conn.commit()
    row = conn.execute("SELECT first_ts FROM import_seen WHERE uid=?", (uid,)).fetchone()
    return int(row["first_ts"]) if row else now


def _import_path(uid: str, name: str, ext: str, ts: int) -> Path:
    """Where one imported photo lands.

    Nothing client-supplied survives into a path segment: the stem is stripped
    to a safe alphabet and the extension is one of a fixed set, checked by the
    caller. The uid fragment keeps two phones' IMG_0001 apart.
    """
    stem = IMPORT_STEM.sub("", os.path.splitext(str(name))[0])[:40] or "photo"
    # Split the id fragment with a dash so nametime.parse cannot read a capture
    # date out of a run of hex digits that happens to look like 20240115.
    tag = f"{uid[14:18]}-{uid[18:22]}"
    day = datetime.datetime.utcfromtimestamp(ts)
    folder = db.IMPORT_DIR / f"{day.year:04d}" / f"{day.month:02d}"
    return folder / f"{stem}_{tag}{ext}"


def _import_write(uid: str, change, body: bytes, ext: str) -> Path | None:
    """Put one downloaded import on disk. None if the path would escape."""
    taken = change.get("taken_ts")
    stamp = int(taken) if isinstance(taken, (int, float)) and taken else int(time.time())
    target = _import_path(uid, change.get("name", ""), ext, stamp)
    # Belt and braces over the stem and extension sanitising in _import_path:
    # whatever the pieces were, the result has to land inside the import folder.
    root = db.IMPORT_DIR.resolve()
    if not str(Path(os.path.normpath(target)).resolve()).startswith(str(root) + os.sep):
        return None
    target.parent.mkdir(parents=True, exist_ok=True)
    if not target.exists():
        tmp = target.with_suffix(target.suffix + ".part")
        tmp.write_bytes(body)
        os.replace(tmp, target)
    return target


def _already_indexed(conn, size: int, digest: str) -> bool:
    """Whether this exact file is already in the library.

    Narrowed by size first, exactly as dupes does it: two files cannot be
    identical unless their sizes match, so a phone sending its whole camera roll
    reads a handful of library files off disk rather than all of them. The hash
    it computes is kept, so the work is done once per library file however many
    uploads pass through here.
    """
    for row in conn.execute(
        "SELECT id, path, mtime, content_hash, hashed_mtime FROM photos"
        " WHERE missing=0 AND filesize=?",
        (size,),
    ).fetchall():
        known = row["content_hash"] if row["hashed_mtime"] == row["mtime"] else None
        if known is None:
            known = dupes.file_hash(row["path"])
            if known is None:
                continue  # unreadable now; it cannot be shown to be the same file
            with db.write_lock:
                conn.execute(
                    "UPDATE photos SET content_hash=?, hashed_mtime=? WHERE id=?",
                    (known, row["mtime"], row["id"]),
                )
                conn.commit()
        if known == digest:
            return True
    return False


def _import_drop(bucket, keys, *targets) -> None:
    """Clear an import's image objects out of the bucket."""
    for key in targets:
        if key in keys:
            try:
                bucket.delete(key)
            except r2.R2Error:
                pass  # the janitor sweeps it later


def _import_photo(conn, bucket, change) -> tuple[int, bool, int]:
    """Land one photo uploaded from the viewer.

    Returns (imported, keep_queued, already_here).

    Never raises: the caller uses the second value to decide whether the inbox
    object stays for another try. The split matters - a transient failure
    (network, disk, a locked database) must NOT consume the only copy of a photo
    that is no longer on the phone, so those keep the op queued, while a
    validation failure that re-running cannot fix drops it.
    """
    now = int(time.time())
    uid = str(change.get("uid", ""))
    if not IMPORT_ID.match(uid):
        return 0, False, 0  # not a shape this machine wrote; nothing to retry

    first_seen = _import_first_seen(conn, uid, now)
    expired = now - first_seen > IMPORT_DEADLINE
    if db.get_setting("cloud_import_enabled", "0") != "1":
        # Refused for now rather than discarded: switching the setting on within
        # the deadline picks these up on the next sync. The Worker's quota is
        # what stops a machine that never opts in from filling the bucket.
        return 0, not expired, 0

    ext = str(change.get("ext", "")).lower()
    if ext not in IMPORT_EXTS:
        ext = ".jpg"
    proxy_key = f"{snapshot.IMPORT_PREFIX}{uid}.jpg"
    full_key = f"{snapshot.IMPORT_PREFIX}{uid}.orig"

    try:
        keys = set(bucket.list_keys(prefix=f"{snapshot.IMPORT_PREFIX}{uid}"))
        have_full = full_key in keys
        # The original is still on its way and there is time left to wait. The
        # proxy alone would publish a downscaled photo we would then never
        # replace, so let the op sit rather than settling early.
        if not have_full and not expired and now - first_seen < IMPORT_GRACE:
            return 0, True, 0
        # The original first, the proxy as a fallback. The fallback is not
        # theoretical: the original may be a HEIC this machine cannot decode
        # (pillow_heif missing or blocked), while the proxy is a plain JPEG the
        # browser made, so settling for it rescues the photo instead of losing
        # it. Nothing undecodable is ever put in the library - the scanner
        # indexes unreadable files because they are already yours, but an upload
        # that will not open is a failed upload.
        candidates = []
        if have_full:
            candidates.append((full_key, str(change.get("sha256") or ""), ext))
        if proxy_key in keys:
            candidates.append((proxy_key, str(change.get("proxy_sha256") or ""), ".jpg"))
        if not candidates:
            return 0, False, 0  # both halves gone: nothing to land, nothing to retry

        target = meta = None
        for source_key, expect, want_ext in candidates:
            body = bucket.get(source_key)
            if not body or len(body) > IMPORT_MAX_BYTES:
                continue
            digest = hashlib.sha256(body).hexdigest()
            if expect and digest != expect:
                # Truncated in transit. Worth another sync in case the object was
                # still being written, but not past the deadline.
                return 0, not expired, 0
            # This exact file is already in the library. The phone skips what it
            # has sent before and what the snapshot names, but neither of those
            # sees a copy that arrived here by cable and was renamed on the way,
            # and one photo is not worth keeping twice.
            if _already_indexed(conn, len(body), digest):
                _import_drop(bucket, keys, proxy_key, full_key)
                with db.write_lock:
                    conn.execute("DELETE FROM import_seen WHERE uid=?", (uid,))
                    conn.commit()
                return 0, False, 1
            candidate = _import_write(uid, change, body, want_ext)
            if candidate is None:
                return 0, False, 0
            probe = photometa.read(str(candidate))
            if not probe.get("error"):
                target, meta = candidate, probe
                break
            candidate.unlink(missing_ok=True)
        if target is None:
            return 0, False, 0  # nothing here decodes; retrying will not change that

        # Registered before the row is written, so the scan that follows treats
        # this as an ordinary library folder rather than pruning what it finds.
        db.add_root(str(db.IMPORT_DIR))

        # The desktop is authoritative - meta came from Pillow reading the file
        # it just wrote - so a phone that could not parse its own HEIC still ends
        # up with real coordinates. The phone's reading only fills a gap.
        #
        # It has to fill both gaps, not just the position. When the original
        # cannot be used and the proxy is what landed, the proxy is a canvas
        # re-encode carrying no EXIF at all, so photometa finds no capture time
        # either and falls back to the file's own date - which is the moment it
        # was written here, not when the photo was taken. The phone read the
        # original before it downscaled it, and that reading is the only copy of
        # those two facts left.
        if meta["lat"] is None and isinstance(change.get("lat"), (int, float)):
            meta["lat"], meta["lon"] = float(change["lat"]), float(change["lon"])
        taken = change.get("taken_ts")
        if meta["taken_src"] != "exif" and isinstance(taken, (int, float)) and taken:
            meta["taken_ts"] = int(taken)
            meta["taken_src"] = "phone"
        with db.write_lock:
            photo_id, _ = scanner.upsert(conn, meta, now)
            conn.execute("DELETE FROM import_seen WHERE uid=?", (uid,))
            conn.commit()
        thumbs.build(photo_id, str(target), int(db.get_setting("snapshot_thumb_size", 160)))

        _import_drop(bucket, keys, proxy_key, full_key)
        return 1, False, 0
    except (r2.R2Error, OSError, sqlite3.Error, MemoryError):
        # Transient. Keep the op queued so the photo gets another sync, unless
        # it has been failing for a week, at which point it is not transient.
        return 0, not expired, 0
    except Exception:
        return 0, False, 0


def _run() -> None:
    conn = db.connect()
    try:
        if not configured():
            _set(phase="error", error="R2 is not configured")
            return

        bucket = client()

        # Take cloud edits first, so the manifest we publish already reflects them.
        _set(phase="receiving")
        received = _apply_inbox(bucket, conn)
        _set(received=received)
        manifest, files = snapshot.build(
            progress=lambda done, total: _set(done=done, total=total)
        )
        _set(phase="uploading", points=manifest["n"], done=0, total=len(files))

        known = {r["key"] for r in conn.execute("SELECT key FROM synced")}
        pending = [(key, path) for key, path in files.items() if key not in known]
        _set(total=len(pending), skipped=len(files) - len(pending))

        uploaded: list[tuple] = []
        failures: list[str] = []
        now = int(time.time())

        def upload(item):
            """Retry before giving up. R2 drops connections partway through a
            long run - a reset after 9,000 objects is the network being busy,
            not the credentials being wrong, and the whole sync used to abort
            on it. Uploads are idempotent, so retrying costs nothing."""
            key, path = item
            body = Path(path).read_bytes()
            last = None
            for attempt in range(UPLOAD_TRIES):
                try:
                    bucket.put(key, body, "image/jpeg")
                    return key, len(body), None
                except Exception as exc:
                    last = str(exc)
                    if attempt + 1 < UPLOAD_TRIES:
                        time.sleep(UPLOAD_BACKOFF * (2 ** attempt))
            return key, 0, last

        if pending:
            with ThreadPoolExecutor(max_workers=4) as pool:
                for key, size, error in pool.map(upload, pending):
                    if error:
                        failures.append(f"{key}: {error}")
                    else:
                        uploaded.append((key, size, now))
                    with _lock:
                        _state["done"] += 1
                        if not error:
                            _state["uploaded"] += 1
                            _state["bytes"] += size
                    if len(failures) > MAX_FAILURES:
                        break

        if uploaded:
            with db.write_lock:
                conn.executemany(
                    "INSERT OR REPLACE INTO synced(key, size, uploaded_ts) VALUES (?,?,?)",
                    uploaded,
                )
                conn.commit()

        # Whatever did land is still worth publishing: the manifest and the
        # viewer go up regardless, and the next sync picks up what is missing,
        # because `synced` already records everything that succeeded.
        if failures:
            _set(error=f"{len(failures)} thumbnail(s) still to upload - run Sync again")

        # Viewer files only move when their own contents change.
        known = json.loads(db.get_setting("viewer_hashes", "") or "{}")
        digests = {}
        for key, path in viewer_files():
            body = path.read_bytes()
            digests[key] = hashlib.sha1(body).hexdigest()
            if known.get(key) != digests[key]:
                bucket.put(key, body, VIEWER_TYPES[path.suffix])
                with _lock:
                    _state["uploaded"] += 1
                    _state["bytes"] += len(body)
        if digests != known:
            db.set_setting("viewer_hashes", json.dumps(digests))

        body = snapshot.manifest_bytes(manifest)
        bucket.put(snapshot.MANIFEST_KEY, body, "application/json")
        with _lock:
            _state["uploaded"] += 1
            _state["bytes"] += len(body)

        # Drop thumbnails for photos that are no longer in the library. Only keys
        # this app recorded are touched, so a shared bucket stays safe.
        _set(phase="pruning")
        stale = [
            r["key"]
            for r in conn.execute("SELECT key FROM synced WHERE key LIKE 't/%'")
            if r["key"] not in files
        ]
        for key in stale:
            try:
                bucket.delete(key)
                with db.write_lock:
                    conn.execute("DELETE FROM synced WHERE key=?", (key,))
                    conn.commit()
                with _lock:
                    _state["deleted"] += 1
            except Exception:
                pass  # a failed delete only costs storage; retried next sync

        # Import objects are normally cleaned up by the drain that consumes
        # them. Anything still here past the deadline lost its other half, or
        # belongs to an op that has already aged out, and would otherwise sit in
        # the bucket eating the free tier forever. The ms-epoch that begins the
        # key is the Worker's own clock, not a phone's.
        cutoff = (time.time() - IMPORT_DEADLINE) * 1000
        try:
            for key in bucket.list_keys(prefix=snapshot.IMPORT_PREFIX):
                stamp = key[len(snapshot.IMPORT_PREFIX):].split("-", 1)[0]
                if stamp.isdigit() and int(stamp) < cutoff:
                    try:
                        bucket.delete(key)
                        with _lock:
                            _state["deleted"] += 1
                    except r2.R2Error:
                        pass
        except r2.R2Error:
            pass

        db.set_setting("last_sync_ts", int(time.time()))
        _set(phase="done")
    except r2.R2Error as exc:
        _set(phase="error", error=exc.message)
    except Exception as exc:
        _set(phase="error", error=f"{type(exc).__name__}: {exc}")
    finally:
        _set(running=False, finished=time.time())


def maybe_sync_after_scan() -> None:
    if db.get_setting("sync_on_scan", "1") == "1" and configured():
        start()


# --------------------------------------------------------------------- watcher
#
# A photo added on a phone sat in the bucket until someone ran a sync here, which
# is a strange thing to ask of a machine that is switched on and idle. This looks
# for work and starts one.
#
# It watches keys rather than counting them, and both prefixes rather than the
# inbox alone. An import whose full-resolution half has not arrived is left
# queued on purpose, so its inbox key is still there on the next look: counting
# would see work every time and sync in a loop forever. A new key is new work,
# and the arriving `.orig` is itself a new key, which is exactly the moment that
# import wants another try.
WATCH_INTERVAL = 60  # seconds

_watch_stop = threading.Event()
_watch_thread: threading.Thread | None = None


def _pending_keys(bucket) -> set[str]:
    return set(bucket.list_keys(prefix=snapshot.INBOX_PREFIX)) | set(
        bucket.list_keys(prefix=snapshot.IMPORT_PREFIX)
    )


def _watch_seen() -> set[str]:
    """What the last look found.

    In the database rather than in memory, because two different processes do
    this now: the app while it is open, and collect.py from a scheduled task
    while it is not. Sharing the record is what stops the second one syncing
    over work the first has already seen.
    """
    try:
        return set(json.loads(db.get_setting("cloud_watch_seen", "[]") or "[]"))
    except (ValueError, TypeError):
        return set()


def _set_watch_seen(keys: set[str]) -> None:
    db.set_setting("cloud_watch_seen", json.dumps(sorted(keys)))


def _watch_once() -> bool:
    """One look at the bucket. True if it started a sync."""
    if _state["running"] or not configured():
        return False
    if db.get_setting("cloud_watch_enabled", "1") != "1":
        return False

    keys = _pending_keys(client())
    fresh = keys - _watch_seen()
    # Forget what has been drained, so the same key arriving again later still
    # counts as new.
    _set_watch_seen(keys)
    if not fresh:
        return False
    return start()


def _watch_loop(interval: int) -> None:
    # One list of each prefix per pass: two Class A operations a minute against a
    # million-a-month allowance, and nothing at all is transferred.
    while not _watch_stop.wait(interval):
        try:
            _watch_once()
        except (r2.R2Error, OSError, sqlite3.Error):
            pass  # a bucket that cannot be reached now is worth another look later
        except Exception:
            pass


def start_watching(interval: int = WATCH_INTERVAL) -> None:
    """Begin looking for work left in the bucket. Idempotent."""
    global _watch_thread
    if _watch_thread and _watch_thread.is_alive():
        return
    _watch_stop.clear()
    _watch_thread = threading.Thread(target=_watch_loop, args=(interval,), daemon=True)
    _watch_thread.start()


def stop_watching() -> None:
    _watch_stop.set()


def reset_remote_state() -> None:
    """Forget what the bucket contains, so the next sync re-uploads everything."""
    conn = db.connect()
    with db.write_lock:
        conn.execute("DELETE FROM synced")
        conn.commit()
    db.set_setting("viewer_hashes", "")
